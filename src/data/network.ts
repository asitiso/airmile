function expandDays(spec: string): number[] {
  if (spec === "*") return [1, 2, 3, 4, 5, 6, 7];
  return [...spec].map((ch) => Number(ch));
}

function flags(code: string): { y: boolean; j: boolean; f: boolean } {
  return { y: true, j: code.includes("J"), f: code.includes("F") };
}

function parse(raw: string): Flight[] {
  const flights: Flight[] = [];
  const seen = new Set<string>();
  const claim = (id: string) => {
    if (!seen.has(id)) {
      seen.add(id);
      return id;
    }
    let n = 2;
    while (seen.has(`${id}#${n}`)) n += 1;
    const next = `${id}#${n}`;
    seen.add(next);
    return next;
  };
  let airline: Airline = "KE";
  let from = "";
  let to = "";
  for (const line of raw.split("\n")) {
    const text = line.trim();
    if (!text) continue;
    const head = text.match(/^(KE|OZ)\s+([A-Z]{3})\s+([A-Z]{3})$/);
    if (head) {
      airline = head[1] as Airline;
      from = head[2];
      to = head[3];
      continue;
    }
    const parts = text.split("|").map((p) => p.trim());
    if (parts.length !== 2) throw new Error(`노선 형식 오류: ${text}`);
    const go = parts[0].split(/\s+/);
    const back = parts[1].split(/\s+/);
    if (go.length !== 7 || back.length !== 4) throw new Error(`편 형식 오류: ${text}`);
    const cab = flags(go[6]);
    const days = expandDays(go[4]);
    const goNo = `${airline}${go[0]}`;
    const backNo = `${airline}${back[0]}`;
    flights.push({
      id: claim(`${goNo}-${from}-${to}`),
      airline,
      no: goNo,
      from,
      to,
      dep: go[1],
      arr: go[2],
      plus: Number(go[3]),
      days,
      eq: go[5],
      ...cab,
    });
    flights.push({
      id: claim(`${backNo}-${to}-${from}`),
      airline,
      no: backNo,
      from: to,
      to: from,
      dep: back[1],
      arr: back[2],
      plus: Number(back[3]),
      days,
      eq: go[5],
      ...cab,
    });
  }
  return flights;
}

